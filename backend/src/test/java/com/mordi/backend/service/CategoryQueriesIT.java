package com.mordi.backend.service;

import com.mordi.backend.dto.CategoryRequest;
import com.mordi.backend.dto.GoalRequest;
import com.mordi.backend.model.Category;
import com.mordi.backend.model.Goal;
import com.mordi.backend.model.User;
import com.mordi.backend.repository.BehaviorRepository;
import com.mordi.backend.repository.CategoryRepository;
import com.mordi.backend.repository.GoalMemberRepository;
import com.mordi.backend.repository.GoalMessageRepository;
import com.mordi.backend.repository.GoalRepository;
import com.mordi.backend.repository.UserRepository;
import jakarta.persistence.EntityManager;
import java.util.UUID;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.dao.DataIntegrityViolationException;
import org.junit.jupiter.api.condition.EnabledIfEnvironmentVariable;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.jdbc.AutoConfigureTestDatabase;
import org.springframework.boot.test.autoconfigure.orm.jpa.DataJpaTest;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * Categories, goal icons and planned days against a real PostgreSQL migrated
 * by Flyway: the derived queries, the update that clears a deleted category
 * off its goals, the case-blind unique index, the cascade on account deletion,
 * and V20's planned_days column with its range check. The unit tests mock all
 * of these. Each test's rows are rolled back.
 *
 *   MORDI_IT_DB=1 SPRING_DATASOURCE_URL=jdbc:postgresql://localhost:5432/mordi \
 *   SPRING_DATASOURCE_PASSWORD=... ./mvnw test -Dtest=CategoryQueriesIT
 */
@DataJpaTest
@AutoConfigureTestDatabase(replace = AutoConfigureTestDatabase.Replace.NONE)
@EnabledIfEnvironmentVariable(named = "MORDI_IT_DB", matches = "1")
class CategoryQueriesIT {

    @Autowired private UserRepository users;
    @Autowired private GoalRepository goals;
    @Autowired private CategoryRepository categories;
    @Autowired private BehaviorRepository behaviors;
    @Autowired private GoalMemberRepository members;
    @Autowired private GoalMessageRepository messages;
    @Autowired private EntityManager em;

    private CategoryService categoryService;
    private GoalService goalService;
    private User sam;
    private User alex;

    @BeforeEach
    void setUp() {
        categoryService = new CategoryService(categories, goals, users);
        goalService = new GoalService(goals, users, behaviors, members, messages, categories);
        sam = person("Sam");
        alex = person("Alex");
    }

    private User person(String name) {
        User user = new User();
        user.setName(name);
        user.setEmail(name.toLowerCase() + "-" + UUID.randomUUID() + "@it.mordi");
        user.setPassword("x");
        return users.save(user);
    }

    private Category category(User owner, String name, String icon) {
        CategoryRequest request = new CategoryRequest();
        request.setName(name);
        request.setIcon(icon);
        return categoryService.createCategory(owner.getEmail(), request);
    }

    private Goal goal(User owner, String title, String category, String icon) {
        GoalRequest request = new GoalRequest();
        request.setTitle(title);
        request.setCategory(category);
        request.setIcon(icon);
        return goalService.createGoal(owner.getEmail(), request);
    }

    @Test
    void theDerivedQueriesListCountAndFindNamesInAnyCase() {
        category(sam, "Reading", "book");
        Category music = category(sam, "music", "music");
        category(alex, "Reading", "book");
        em.flush();

        assertThat(categories.findByUserOrderByNameAsc(sam)).extracting(Category::getName)
            .containsExactlyInAnyOrder("music", "Reading");
        assertThat(categories.countByUser(sam)).isEqualTo(2);
        assertThat(categories.existsByUserAndNameIgnoreCase(sam, "READING")).isTrue();
        assertThat(categories.existsByUserAndNameIgnoreCase(sam, "Cooking")).isFalse();
        assertThat(categories.existsByUserAndNameIgnoreCaseAndIdNot(sam, "Music", music.getId())).isFalse();
        assertThat(categories.existsByUserAndNameIgnoreCaseAndIdNot(sam, "reading", music.getId())).isTrue();
    }

    @Test
    void theIndexRefusesTheSameNameInAnotherCase() {
        category(sam, "Reading", "book");
        em.flush();

        Category twin = new Category();
        twin.setUser(sam);
        twin.setName("READING");
        twin.setIcon("book");

        // The id is generated by the database, so save() inserts at once: the
        // index refuses it there, not at the next flush.
        assertThatThrownBy(() -> {
            categories.save(twin);
            em.flush();
        }).isInstanceOf(DataIntegrityViolationException.class);
    }

    @Test
    void deletingACategoryClearsItFromGoalsAndLeavesTheirIcons() {
        Category reading = category(sam, "Reading", "book");
        Goal novel = goal(sam, "A chapter a night", reading.getKey(), "pen");
        Goal plain = goal(sam, "Run", "fitness", null);
        em.flush();
        em.clear();

        // Listed goals carry the category's name and icon.
        Goal listed = goalService.getActiveGoals(sam.getEmail()).stream()
            .filter(g -> g.getId().equals(novel.getId())).findFirst().orElseThrow();
        assertThat(listed.getCategory()).isEqualTo("custom:" + reading.getId());
        assertThat(listed.getCategoryName()).isEqualTo("Reading");
        assertThat(listed.getCategoryIcon()).isEqualTo("book");
        em.clear();

        categoryService.deleteCategory(sam.getEmail(), reading.getId());
        em.flush();
        em.clear();

        Goal after = goals.findById(novel.getId()).orElseThrow();
        assertThat(after.getCategory()).isNull();
        assertThat(after.getIcon()).isEqualTo("pen");
        assertThat(goals.findById(plain.getId()).orElseThrow().getCategory()).isEqualTo("fitness");
        assertThat(categories.findById(reading.getId())).isEmpty();
    }

    @Test
    void plannedDaysRoundTripThroughMigrationV20() {
        GoalRequest request = new GoalRequest();
        request.setTitle("Morning run");
        request.setTargetPerWeek(5);
        request.setPlannedDays(0b001_0101); // Monday, Wednesday, Friday
        Goal run = goalService.createGoal(sam.getEmail(), request);
        Goal read = goal(sam, "Read", null, null);
        em.flush();
        em.clear();

        Goal loaded = goals.findById(run.getId()).orElseThrow();
        assertThat(loaded.getPlannedDays()).isEqualTo((short) 0b001_0101);
        assertThat(loaded.getTargetPerWeek()).isEqualTo(3);
        assertThat(goals.findById(read.getId()).orElseThrow().getPlannedDays()).isNull();

        GoalRequest clear = new GoalRequest();
        clear.setPlannedDays(0);
        goalService.updateGoal(sam.getEmail(), run.getId(), clear);
        em.flush();
        em.clear();
        assertThat(goals.findById(run.getId()).orElseThrow().getPlannedDays()).isNull();
    }

    @Test
    void theCheckConstraintRefusesAnOutOfRangeMask() {
        Goal goal = goal(sam, "Run", null, null);
        em.flush();

        assertThatThrownBy(() -> em.createNativeQuery("UPDATE goals SET planned_days = 128 WHERE id = :id")
            .setParameter("id", goal.getId())
            .executeUpdate())
            .isInstanceOf(Exception.class);
    }

    @Test
    void aGoalCannotUseSomeoneElsesCategory() {
        Category theirs = category(alex, "Reading", "book");
        em.flush();

        assertThatThrownBy(() -> goal(sam, "Read", theirs.getKey(), null))
            .isInstanceOf(IllegalArgumentException.class);
    }

    @Test
    void deletingTheAccountTakesItsCategories() {
        Category reading = category(sam, "Reading", "book");
        em.flush();

        users.deleteUserById(sam.getId());
        em.flush();
        em.clear();

        assertThat(categories.findById(reading.getId())).isEmpty();
    }
}
